-- TraffLabels cost tracking (per-order and general business costs).
-- Apply by hand on the Supabase project (qbdpcwcpltsznqnrrkny) after review.
-- Do not rely on app boot to create this table.
--
-- Access is server-side through DATABASE_URL (the table owner, which bypasses
-- RLS). RLS is enabled with no policies, and anon/authenticated get no
-- privileges at all, so the Data API cannot read or write costs.
-- service_role is granted ALL explicitly (Supabase stopped auto-granting
-- table privileges on 30 October 2026). TRUNCATE, REFERENCES and TRIGGER are
-- never granted to anon or authenticated.
--
-- Amounts are whole cents in AUD. gst_included = true means amount_cents is the
-- GST-inclusive receipt total; the app removes 1/11 to get the ex-GST cost
-- because TraffLabels (Golf Chariots (Aust) Pty Ltd) is GST registered.

CREATE TABLE IF NOT EXISTS public.trafflabels_costs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cost_date date NOT NULL,
  amount_cents integer NOT NULL CHECK (amount_cents > 0 AND amount_cents <= 100000000),
  gst_included boolean NOT NULL DEFAULT true,
  category text NOT NULL CHECK (category IN (
    'postage', 'materials', 'stripe_fees', 'tools', 'software', 'other'
  )),
  description text NOT NULL DEFAULT '',
  order_id text REFERENCES public.trafflabels_orders (id) ON DELETE SET NULL,
  receipt_ref text NOT NULL DEFAULT '',
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.trafflabels_costs IS
  'TraffLabels costs. order_id null = general cost. Written by the app with the database owner role.';

CREATE INDEX IF NOT EXISTS trafflabels_costs_date_idx ON public.trafflabels_costs (cost_date DESC);
CREATE INDEX IF NOT EXISTS trafflabels_costs_order_idx ON public.trafflabels_costs (order_id);

ALTER TABLE public.trafflabels_costs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.trafflabels_costs FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.trafflabels_costs_id_seq FROM PUBLIC;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON TABLE public.trafflabels_costs FROM anon';
    EXECUTE 'REVOKE ALL ON SEQUENCE public.trafflabels_costs_id_seq FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON TABLE public.trafflabels_costs FROM authenticated';
    EXECUTE 'REVOKE ALL ON SEQUENCE public.trafflabels_costs_id_seq FROM authenticated';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    EXECUTE 'GRANT ALL ON TABLE public.trafflabels_costs TO service_role';
    EXECUTE 'GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.trafflabels_costs_id_seq TO service_role';
  END IF;
END $$;

