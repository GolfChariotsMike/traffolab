-- 17 Nov 2026 bulk buy: 180 ABS 3M-backed sheets, 300x200 mm, US$568 landed
-- at 1.483068 = A$842.38, no Australian GST. 60 Red/White, 60 White/Black,
-- 60 Yellow/Black. Moved out of trafflabels_costs so the month does not
-- count it as well as the per-order plate costs. Idempotent.
INSERT INTO public.trafflabels_stock_purchases (
  purchased_on, sheet_count, width_mm, height_mm, colour,
  amount_cents, gst_included, notes, created_by, created_at
)
SELECT
  c.cost_date,
  180,
  300,
  200,
  'Red/White, White/Black, Yellow/Black',
  c.amount_cents,
  c.gst_included,
  c.description,
  c.created_by,
  c.created_at
FROM public.trafflabels_costs c
WHERE c.order_id IS NULL
  AND c.category = 'materials'
  AND c.amount_cents = 84238
  AND c.gst_included = false
  AND c.cost_date = DATE '2026-11-17'
  AND c.description LIKE 'ABS laser-engraving double-colour sheets%'
  AND NOT EXISTS (
    SELECT 1
    FROM public.trafflabels_stock_purchases p
    WHERE p.purchased_on = DATE '2026-11-17'
      AND p.sheet_count = 180
      AND p.amount_cents = 84238
  );

DELETE FROM public.trafflabels_costs c
WHERE c.order_id IS NULL
  AND c.category = 'materials'
  AND c.amount_cents = 84238
  AND c.gst_included = false
  AND c.cost_date = DATE '2026-11-17'
  AND c.description LIKE 'ABS laser-engraving double-colour sheets%';

