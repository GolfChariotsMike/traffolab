-- TraffLabels sheet stock. Bulk purchases of engraving sheet, plus a physical
-- count so wastage is the difference between the book balance and the shelf.
-- Apply by hand on the Supabase project (qbdpcwcpltsznqnrrkny) after review.
-- Do not rely on app boot to create these tables.
--
-- Access is server-side through DATABASE_URL (the table owner, which bypasses
-- RLS). The dashboard sign-in is the existing admin email allowlist, so
-- authenticated is not granted anything: Leanne and Mike do not query these
-- tables through the Data API. RLS is enabled with no policies. anon and
-- authenticated get no privileges. service_role is granted ALL explicitly
-- (Supabase stopped auto-granting table privileges on 30 October 2026).
-- ALL for service_role includes TRUNCATE, REFERENCES, and TRIGGER. Those
-- three are never granted to anon or authenticated, and are revoked here.
--
-- Amounts are whole cents in AUD. gst_included = true means amount_cents is
-- the GST-inclusive receipt total. The app prices plate area from the ex-GST
-- landed cost. Purchases are not monthly costs. Each order's material cost
-- is calculated from its plates, so the per-order materials rows copied in
-- on 19 Nov 2026 are removed rather than kept beside that calculation.

CREATE TABLE IF NOT EXISTS public.trafflabels_stock_purchases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchased_on date NOT NULL,
  sheet_count integer NOT NULL CHECK (sheet_count > 0 AND sheet_count <= 1000000),
  width_mm integer NOT NULL CHECK (width_mm > 0 AND width_mm <= 5000),
  height_mm integer NOT NULL CHECK (height_mm > 0 AND height_mm <= 5000),
  colour text NOT NULL DEFAULT '' CHECK (char_length(colour) <= 200),
  amount_cents integer NOT NULL CHECK (amount_cents > 0 AND amount_cents <= 100000000),
  gst_included boolean NOT NULL DEFAULT false,
  notes text NOT NULL DEFAULT '' CHECK (char_length(notes) <= 2000),
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.trafflabels_stock_purchases IS
  'Bulk sheet purchases. Excluded from monthly profit. The app draws each order''s plate area down against the weighted average landed cost.';

CREATE INDEX IF NOT EXISTS trafflabels_stock_purchases_date_idx
  ON public.trafflabels_stock_purchases (purchased_on DESC);

CREATE TABLE IF NOT EXISTS public.trafflabels_stock_counts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  counted_on date NOT NULL,
  sheets_on_hand integer NOT NULL CHECK (sheets_on_hand >= 0 AND sheets_on_hand <= 1000000),
  notes text NOT NULL DEFAULT '' CHECK (char_length(notes) <= 2000),
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.trafflabels_stock_counts IS
  'Physical 300x200 mm sheets on the shelf. The latest count is compared with the book balance to show wastage.';

CREATE INDEX IF NOT EXISTS trafflabels_stock_counts_date_idx
  ON public.trafflabels_stock_counts (counted_on DESC, id DESC);

ALTER TABLE public.trafflabels_stock_purchases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trafflabels_stock_counts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.trafflabels_stock_purchases FROM PUBLIC;
REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE public.trafflabels_stock_purchases FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.trafflabels_stock_purchases_id_seq FROM PUBLIC;

REVOKE ALL ON TABLE public.trafflabels_stock_counts FROM PUBLIC;
REVOKE TRUNCATE, REFERENCES, TRIGGER ON TABLE public.trafflabels_stock_counts FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.trafflabels_stock_counts_id_seq FROM PUBLIC;

